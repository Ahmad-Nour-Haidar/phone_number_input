abstract final class Countries {
  /// Returns the country with the ISO 3166-1 alpha-2 [isoCode], e.g. `SY`,
  /// or null when there is none. The code is matched case-insensitively.
  static Country? byIsoCode(String isoCode) =>
      _byIsoCode[isoCode.toUpperCase()];

  /// Returns the country of [dialCode], e.g. `+963` or `963`, or null when
  /// there is none.
  ///
  /// A calling code shared by several countries returns the main one, e.g.
  /// `+1` returns the United States and `+7` returns Russia. Dial codes that
  /// include an area code, such as `+1264`, return their own country.
  static Country? byDialCode(String dialCode) {
    final digits = dialCode.startsWith('+') ? dialCode.substring(1) : dialCode;
    final callingCode = int.tryParse(digits);
    if (callingCode == null) {
      return null;
    }
    return byIsoCode(PhoneNumberUtil.regionForCallingCode(callingCode)) ??
        all.where((country) => country.dialCode == '+$digits').firstOrNull;
  }

  /// Returns the countries whose ISO codes are in [isoCodes], in the order
  /// of [all], or all countries when [isoCodes] is null or empty.
  ///
  /// Codes are matched case-insensitively. Unknown codes are ignored.
  static List<Country> filter(Iterable<String>? isoCodes) {
    if (isoCodes == null || isoCodes.isEmpty) {
      return all;
    }
    final codes = {for (final code in isoCodes) code.toUpperCase()};
    return [
      for (final country in all)
        if (codes.contains(country.alpha2Code)) country,
    ];
  }

